/**
 * Memoized per-chapter view with heading ids de-duplicated.
 *
 * A couple of merged tree-study chapters contain two headings whose
 * slugs collide (e.g. "Spot the Difference" in dsa/10). Later occurrences
 * get a numeric suffix (-2, -3, …). Both the rendered heading anchors,
 * the TOC hrefs/keys and the scroll-spy consume this normalized data,
 * so every consumer always shares the exact same ids.
 */
const normalizedChapters = new Map<string, ChapterData>();

export function getChapter(
  bookSlug: string,
  chapterSlug: string
): ChapterData | undefined {
  const key = `/${bookSlug}/${chapterSlug}`;
  const cached = normalizedChapters.get(key);
  if (cached) return cached;
  const raw = chapterRegistry.get(key);
  if (!raw) return undefined;

  const seen = new Set<string>();
  let changed = false;
  const blocks = raw.blocks.map((b) => {
    if (b.type !== "heading") return b;
    if (!seen.has(b.id)) {
      seen.add(b.id);
      return b;
    }
    changed = true;
    let n = 2;
    let id = `${b.id}-${n}`;
    while (seen.has(id)) id = `${b.id}-${++n}`;
    seen.add(id);
    return { ...b, id };
  });

  const normalized = changed ? { meta: raw.meta, blocks } : raw;
  normalizedChapters.set(key, normalized);
  return normalized;
}

export function getQuiz(bookSlug: string, quizSlug: string): QuizData | undefined {
  return quizRegistry.get(`/${bookSlug}/${quizSlug}`);
}

